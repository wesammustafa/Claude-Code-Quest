// The 3D Pip's model (seam S13), generated in code from the guide's own
// approved Pip: the head, ears, antennas and torso from turn.ts's box
// model, every part's size, place and colours from the front-view art in
// rig/pip.rml, and every clip ported from the rig's own timelines. Soft
// low-poly, flat faces, its light baked into vertex colours under one unlit
// material, so the Scene's lights never light him twice.
// `npm run pip:model` writes pip.glb beside this file, the same bytes every
// time; pip-model.test.ts fails when the committed file is not exactly
// what this writes.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { bakeClips, firstPlaces } from "./clips.ts";
import { writeGlb } from "./gltf.ts";
import { pipParts, type PipNode } from "./parts.ts";

/** The committed model, beside this file. */
export const PIP_MODEL_FILE = "pip.glb";

/**
 * The clips, in the model contract's order (contract.ts's PIP_MODEL_CLIPS,
 * which pip-model.test.ts holds this to): written here so this script runs
 * in Node on its own.
 */
export const CLIP_ORDER = [
  "idle",
  "thinking",
  "rest",
  "sleep",
  "greeting",
  "curious",
  "explaining",
  "success",
  "retry",
  "celebration",
  "still",
] as const;

/** Each effect's hidden resting place: where it first shows, kept inside Pip's own bounds so it never moves his measured size. */
function effectRest(places: ReadonlyMap<string, readonly [number, number]>) {
  return (name: string): readonly [number, number] => {
    const [x, y] = places.get(name) ?? [0, 0.5];
    return [
      Math.max(-0.5, Math.min(0.5, x)),
      Math.max(0.01, Math.min(0.99, y)),
    ];
  };
}

/** Pip's node tree at rest. */
export function pipTree(): PipNode {
  return pipParts(effectRest(firstPlaces()));
}

/** The model as a binary glTF (.glb), the same bytes every time. */
export function pipModel(): Uint8Array {
  const root = pipTree();
  return writeGlb(
    root,
    bakeClips(root, CLIP_ORDER),
    "Pip's 3D model, generated by quest/client/pip/model/pip-model.ts (npm run pip:model)",
  );
}

if (import.meta.main) {
  const file = join(import.meta.dirname, PIP_MODEL_FILE);
  const bytes = pipModel();
  writeFileSync(file, bytes);
  console.log(`${file}: ${String(bytes.length)} bytes`);
}
